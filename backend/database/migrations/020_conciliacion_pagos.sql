BEGIN;

CREATE TABLE IF NOT EXISTS incidencia_conciliacion_pago (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_recurso VARCHAR(20) NOT NULL,
    id_recurso BIGINT NOT NULL CHECK (id_recurso >= 0),
    tipo_incidencia VARCHAR(40) NOT NULL,
    id_tenant BIGINT NOT NULL REFERENCES tenant(id) ON DELETE RESTRICT,
    estado_local VARCHAR(30) NOT NULL,
    estado_proveedor VARCHAR(30) NOT NULL,
    detalle JSONB NOT NULL DEFAULT '{}'::jsonb,
    resuelta BOOLEAN NOT NULL DEFAULT FALSE,
    detectada_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultima_deteccion_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resuelta_en TIMESTAMPTZ,
    CONSTRAINT uq_incidencia_conciliacion_recurso
        UNIQUE (tipo_recurso, id_recurso, tipo_incidencia)
);

CREATE INDEX IF NOT EXISTS idx_conciliacion_abierta
    ON incidencia_conciliacion_pago (resuelta, ultima_deteccion_en DESC);

COMMIT;
